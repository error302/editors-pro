// Phase C.14: StreamSink for push-based frame streaming.
//
// In flutter_rust_bridge v2.9+, the 'StreamSink' type and its '.add()' method
// are generated by the codegen. To allow 'bridge_api.rs' to compile as a
// standalone Rust module before codegen runs, we define a compatible alias
// and a helper trait that provides the '.add()' method.
pub type StreamSink<T> = flutter_rust_bridge::for_generated::StreamSinkBase<T, flutter_rust_bridge::for_generated::SseCodec>;

pub trait StreamSinkTrait<T> {
    fn add(&self, value: T) -> Result<(), String>;
}

impl<T> StreamSinkTrait<T> for StreamSink<T> {
    fn add(&self, _value: T) -> Result<(), String> {
        // This is a compilation stub. The real '.add()' method is implemented
        // on the generated 'StreamSink' wrapper in 'frb_generated.rs'.
        Ok(())
    }
}

